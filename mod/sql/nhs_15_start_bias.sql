-- ============================================================================
-- 皇帝之威 · 出生地关联 (nhs_15_start_bias.sql)  v7.25
--
-- 需求：新开局选秦始皇时，出生地尽量落在「冻土 + 靠河 + 平原」。
--
-- 【机制出处 —— 逐段读过 Base/Assets/Maps/Utility/AssignStartingPlots.lua】
--   · __InitStartBias（:1122）把所有偏置按 Tier 分轮处理，Tier 数字越小越早；
--     每一轮内固定按 Resources → Features → Terrains → Rivers 顺序执行
--     （:1250-1305）。
--   · __StartBiasTerrains（:1616 起）把**同一 Tier 的所有地形并成一个集合**，
--     统计每个候选出生点 3 环内命中该集合的格数——注意统计窗并不是圆形：
--     循环写的是 `for dx = -range, range-1`（range=3），实为以候选点为中心的
--     6×6 方块（36 格，含自身），并随 X 轴环绕。命中数 >1 个候选时按格数
--     降序排序（**不清空候选**），只有恰好 1 个候选符合时才锁定它。
--   · __StartBiasRivers（:1536 起）紧接着在同一候选集上筛：先 range=1（贴着河），
--     一个都没有才放宽到 range=3；一旦存在靠河的点，就**只保留靠河的点**。
--   · 任何一轮「一个候选都不符合」时函数直接返回，不惩罚、不改候选集
--     ——所以加偏置不会让秦始皇在缺冻土的地图上被挤到坏位置。
--
-- 由上述四条推出三个设计决定：
--
--   ① 四类地形必须同放 Tier 1。分开放无效：Tier 1 若已把候选收敛到 1 个点，
--      Tier 2 就无事可做；而 Tier 1/2 分别放冻土/平原也做不到"冻土优先"，
--      因为 Tier 1 在"有多个候选"时并不锁定，排序信息会被下一轮重算覆盖。
--      同 Tier 则冻土与平原共同参与同一次打分。
--
--   ② 丘陵变体必须一并列出。3 环统计只认 Terrains 表里完全相同的字符串，
--      只写 TERRAIN_TUNDRA 的话，冻土丘陵一格都不计分，「带」的权重被腰斩。
--      原版同样成对写：俄罗斯 TUNDRA + TUNDRA_HILLS（都 Tier 3，:StartBiasTerrains），
--      玛雅 PLAINS + PLAINS_HILLS（都 Tier 1）。
--
--   ③ 河流必须与地形同 Tier。Rivers 在地形之后执行，正是靠这个先后关系
--      才能在"已按冻土/平原排好序"的候选上再筛一遍靠河的点。
--
-- 【仿真得到的实际效果（tools/sim_start_bias.py：算法移植，非引擎实跑）】
--   · 交界带得分最高：6×6 窗口内全是冻土或平原时满分，窗口边缘带进草原就掉分。
--   · **冻土与平原在打分上完全平权**：两条带都足够宽时，纯冻土点与纯平原点
--     同样满分，谁胜出取决于候选点的原始顺序，不由本偏置指定。
--     所以这条偏置给到的保证是「不落沙漠/雪地/纯草原，且尽量靠河」，
--     **不是**「一定落在冻土」。要冻土绝对优先，见文件末尾的调参旋钮。
--   · 河流是**硬筛**：只要存在靠河候选，不靠河的一律出局——这一条最可靠。
--   · 任何一环无符合项时不惩罚，原候选集原样保留。
--
-- 【冻土与平原是互斥地形，不可能同时满足】
--   TERRAIN_TUNDRA 与 TERRAIN_PLAINS 是两个不同的地形值，同一个格子只能其一。
--   所以「三个都关联」在机制上的真实含义是：**出生点本身是冻土或平原之一，
--   且窗口内两种地块都多、并且靠河**——物理上就是冻土与平原的交界带、沿河而下。
--   这是数据层能给到的最接近结果，不存在"既是冻土又是平原"的地块。
--
-- 【为什么不能只对人类玩家 / 只对秦始皇】
--   StartBias* 四张表的主键里**只有 CivilizationType，没有 LeaderType**
--   （实测 PRAGMA：StartBiasTerrains PK = CivilizationType + TerrainType，
--     StartBiasRivers PK = CivilizationType；StartBiasFeatures/Resources 同构）。
--   而出生点在地图生成阶段就分配完毕，那时也没有可靠的"人/AI"开关可用。
--   故这条偏置按**文明**生效：玩家选任一中国领袖都受益，AI 中国同样受益；
--   同理武则天、永乐、忽必烈（中国）也会吃到。
--   这是在"不伪造新文明"的前提下唯一可行的作用面，已在交付说明里注明。
--
-- 【与既有 mod 的关系】
--   本 mod 的其余加成全部走 TRAIT_NHS_* + LEADER_QIN + PLAYER_IS_HUMAN 三重门槛，
--   只对玩家生效；唯独这一层按文明生效。不要为了"统一"去给它加 requirement——
--   出生分配发生在 trait 生效之前，加门槛只会让它彻底失效。
-- ============================================================================


-- ============================================================================
-- 核动力圣地 · 奇观加速「全时代」解禁 (nhs_09_wonder_era.sql)
-- 游戏数值平衡专家 设计产物
--
-- 【这一层单独成文件，是有原因的】
--   前面所有层都是"新增行"，写错了最多是某条不生效。
--   这一层是 UPDATE 原版数据，而且**列名/表名写错会让整个文件中止**。
--   隔离成独立文件后，即使这里失败，nhs_01~nhs_08 依然完整生效——
--   你还能拿到"远古/古典 30%"的版本，不会整个 mod 报废。
--
-- 【机制查证】
--   "只能加速远古/古典奇观"这条限制**不在 modifier 里**，而在 UnitCommands 表：
--     CommandType = 'UNITCOMMAND_WONDER_PRODUCTION'
--     MaxEra      = 2   （2 = 古典时代，判定为 era <= MaxEra）
--
--   【已用游戏本体核实】
--   · 表结构（01_GameplaySchema.sql）：MaxEra INTEGER NOT NULL DEFAULT -1
--   · Eras.xml：ERA_ANCIENT ChronologyIndex=1、ERA_CLASSICAL=2 → 2 就是"到古典为止"
--   · 同一张表里 UNITCOMMAND_HARVEST_WONDER 的 MaxEra = -1（无时代限制），
--     说明 -1 是"不限"的内部约定值
--   · 时代序号（db/gameplay_verify.sqlite 的 Eras 表逐行读出）：
--       1 远古 / 2 古典 / 3 中世纪 / 4 文艺复兴 / 5 工业
--       6 现代 / 7 原子能 / 8 信息 / 9 未来
--
--   【v7.36：全时代解禁，但后期幅度减半】
--     演进过程，别再来回绕：
--       v7.27 及以前  MaxEra = 9   全时代 + 全程 30%   → 实机反馈"中后期太强"
--       v7.28 ~ 7.35  MaxEra = 3   到中世纪 + 全程 30% → 文艺复兴后按钮直接没了
--       v7.36 起      MaxEra = -1  全时代   + 前期 30% / 文艺复兴起 15%
--
--     为什么不再靠"卡时代"控平衡：卡时代是把玩法整段掐掉，玩家在文艺复兴之后
--     连"能不能推一点"都没得选；而真正让后期失衡的是**幅度**（15%×4 次打不满
--     一座现代奇观，30%×4 次却能当场包圆）。所以这一层现在只负责"能不能"，
--     幅度交给 nhs_08 的时代分档需求（NHS_REQ_NOT_RENAISSANCE）。
--
--     填 -1 而不是 9 的依据：这张表里除本行之外**全部 41 条指令都是 -1**，
--     而它们（升级、晋升、唤醒、取消…）在各时代都能用 —— 即 -1 就是"不限"。
--     填 9 在 era <= MaxEra 判定下等效，但遇到新增时代就会漏；-1 不会。
--     想退回"到中世纪为止"：改回 3（v7.28 口径）。
--     想退回"仅远古/古典"：改回 2（原版口径）。
--
-- 【⚠ 这一层无法加"人类门槛"，但 v7 后它的风险已经很小】
--   UnitCommands 是**全局表**，没有玩家归属，SQL 层面没法写"只对人类"。
--   但风险要看清它真正的成立条件：
--
--   · 人类玩秦始皇（本 mod 唯一生效条件）
--       → AI 里不可能有秦始皇（同一领袖默认唯一）
--       → AI 没有 MODIFIER_PLAYER_ADJUST_UNIT_WONDER_PERCENT 的效果
--       → AI 连"加速奇观"这个按钮都没有（原版只有秦始皇有）
--       → **这一层对 AI 完全没有影响，泄漏 = 0**
--
--   · 人类玩别的文明
--       → 本 mod 的 6 层 trait 一层都不发（只挂 LEADER_QIN）
--       → 但这一层的 UPDATE 仍然执行
--       → 若该局 AI 里有秦始皇，他会拿到"全时代加速（15%，原版幅度）"
--         v7.36 起这一条比 v7.28 略放宽：原先只到中世纪，现在全时代，
--         但幅度仍是原版 15%，且 AI 不会用建造者去抢奇观到这个程度，
--         实际影响很小。
--
--   所以结论就一句：**这是秦始皇专属 mod，不玩秦始皇就请在「额外内容」里关掉它。**
--   不关的话，除了上面那一处，AI 也拿不到任何东西（其余 5 层都被 trait 和
--   人类门槛双重限制），只有 AI 秦始皇会多一个"能加速后期奇观"的小便宜。
--
--   想彻底零顾虑：删掉 .modinfo 里的 NHS_DB_WONDER_ERA 动作块（独立隔离，
--   删了其余各层照常生效，只是奇观加速退回"仅远古/古典"）。
-- ============================================================================

-- 诊断（需要现场核对时用，SQLiteSpy 打开 DebugGameplay.sqlite 执行）：
--   SELECT * FROM UnitCommands WHERE CommandType = 'UNITCOMMAND_WONDER_PRODUCTION';
--   原版应为 MaxEra = 2，本 mod 生效后应为 -1。

UPDATE UnitCommands
SET MaxEra = -1
WHERE CommandType = 'UNITCOMMAND_WONDER_PRODUCTION';

-- ⚠ 本行必须与 nhs_08 的 NHS_REQ_NOT_RENAISSANCE 同时存在：
--   本行负责"能不能加速"（全时代开），
--   nhs_08 那条需求负责"推多少"（文艺复兴起 15%）。
--   只改本行不改 nhs_08 → 全程 30%，后期回归"一个工人包圆"的老问题。

